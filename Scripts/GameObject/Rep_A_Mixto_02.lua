require( "PGStateMachine" )
require( "PGSpawnUnits" )
require("PGStoryMode")

function Definitions()
        Define_State( "State_Init",State_Init )

	unit_list = { "Republic_CloneTrooper_Mixto_Squad_MKII", "Republic_Clon_Sniper_Phase2_Squad", "Republic_Assault_Flame_Squad", "Republic_Assault_Squad", "Rep_Hovermoto_Phase2_Squad", "Republic_Engineer_Squad" }
		

end

function State_Init( message )
        if message ~= OnEnter then return end 
		Sleep(5)
		if Get_Game_Mode() ~= "Galactic" then ScriptExit() end
		
		SpawnList(unit_list, Object.Get_Planet_Location(), Object.Get_Owner(), true, false)
	
	Object.Despawn() 
        Sleep( 1.0 )
	ScriptExit()
end










